// Prueba del formulario abierto (sin enlace personal) contra el simulador
import { chromium, devices } from 'playwright';
const filas = async () => (await (await fetch('http://localhost:8787/__rows')).json()).map((r) => r.slice(1, 5).map(String));
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const saltar = async (p) => { await p.evaluate(() => { document.querySelector('#escena')?.remove(); document.body.classList.remove('bloqueado'); document.querySelector('#invitacion').classList.add('visible'); document.querySelectorAll('.esc').forEach((e) => e.classList.add('on')); }); await p.evaluate(() => document.querySelector('#rsvp').scrollIntoView({ block: 'center' })); };
const res = {};
const ctx = await b.newContext({ ...devices['iPhone 13'] });
const p = await ctx.newPage();
await p.goto('http://localhost:8080/'); await saltar(p); await p.waitForTimeout(800);
res.editable = !(await p.getAttribute('#nombre', 'readonly'));
res.aviso = await p.textContent('#aviso');
await p.fill('#nombre', 'María'); await p.click('.opcion:has(input[value="yes"])'); await p.click('#enviar');
res.soloNombre = await p.textContent('#mensaje');
await p.fill('#nombre', 'María López'); await p.click('#enviar');
await p.waitForSelector('.listo', { timeout: 10000 });
await p.screenshot({ path: 'capturas/abierto-1-confirmado.png' });
res.tras1 = await filas();
await p.reload(); await saltar(p); await p.waitForSelector('.listo', { timeout: 10000 });
res.alRecargar = (await p.textContent('.listo .cuerpo')).trim();
await p.click('.listo .enlace'); res.nombreBloqueado = !!(await p.getAttribute('#nombre', 'readonly'));
await p.click('.opcion:has(input[value="no"])'); await p.click('#enviar'); await p.waitForSelector('.listo');
res.tras2 = await filas();
const ctx2 = await b.newContext({ ...devices['Pixel 7'] });
const p2 = await ctx2.newPage();
await p2.goto('http://localhost:8080/'); await saltar(p2); await p2.waitForTimeout(800);
await p2.fill('#nombre', '  maria   LÓPEZ '); await p2.click('.opcion:has(input[value="yes"])'); await p2.click('#enviar'); await p2.waitForSelector('.listo');
res.otraPersonaMismoNombre = await filas();
const ids = await (await fetch('http://localhost:8787/__ids')).json();
await p2.goto('http://localhost:8080/?i=' + ids[0]); await saltar(p2); await p2.waitForTimeout(1200);
res.enlacePersonal = await p2.inputValue('#nombre');
await p2.screenshot({ path: 'capturas/abierto-2-personal.png' });
console.log(JSON.stringify(res, null, 1));
await b.close();
